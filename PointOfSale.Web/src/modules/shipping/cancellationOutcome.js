const outcomes = new Set(['Confirmed', 'Requested', 'Unsupported', 'ReconciliationRequired'])
const inFlight = new Map()

export function admitCancellationOutcome(data, expectedShipmentId) {
    if (expectedShipmentId && data?.shipmentId !== expectedShipmentId) return { outcome: 'ReconciliationRequired', code: 'CANCELLATION_RESPONSE_TARGET_MISMATCH' }
    if (!data || !outcomes.has(data.outcome)) return { outcome: 'ReconciliationRequired', code: 'CANCELLATION_RESPONSE_UNVERIFIED' }
    if (data.outcome === 'Confirmed' && (!data.operationId || !data.confirmedAtUtc || data.currentStatus !== 'Cancelled' ||
        !['LocalOnly', 'NoExternalShipment', 'CarrierConfirmed'].includes(data.confirmationBasis) ||
        (data.confirmationBasis === 'CarrierConfirmed' && data.externalConfirmationExists !== true))) {
        return { ...data, outcome: 'ReconciliationRequired', code: 'CANCELLATION_RESPONSE_UNVERIFIED' }
    }
    return data
}

// Both callers consume typed outcomes, including HTTP 409. Repeated clicks join
// the command; no replacement operation identity is generated by the client.
export function requestShipmentCancellation(api, shipmentId, reason, config) {
    if (inFlight.has(shipmentId)) return inFlight.get(shipmentId)
    const promise = (async () => {
        try {
            const response = await api.post(`/admin/shipments/${shipmentId}/cancel`, { reason: reason.trim() }, config)
            return admitCancellationOutcome(response.data, shipmentId)
        } catch (error) {
            if (error.response?.status === 409 && outcomes.has(error.response.data?.outcome))
                return admitCancellationOutcome(error.response.data, shipmentId)
            throw error
        } finally { inFlight.delete(shipmentId) }
    })()
    inFlight.set(shipmentId, promise)
    return promise
}
