// Real replacement, failure, discard and whole-StoreConfig rollback journey.
async page => {
    const status = async value => page.evaluate(value => sessionStorage.setItem('homepage-rollback-status', value), value);
    try {
    await status('started');
    const live = page.context().pages().find(p => p.url().includes('ahramstore.localhost'));
    const read = async path => page.evaluate(async path => (await (await import('/src/services/api.js')).default.get(path)).data, path);
    const clean = () => page.waitForFunction(async () => !(await import('/src/modules/storefront/store/index.js')).useBuilderStore.getState().isDirty);
    await page.setViewportSize({ width: 1600, height: 1000 });
    await page.goto('http://localhost:5173/storefront/homepage');
    await page.getByRole('button', { name: /^(Edit|تعديل)$/ }).first().waitFor();
    if ((await page.locator('html').getAttribute('lang')) !== 'en') await page.getByRole('button', { name: 'EN', exact: true }).click();
    await page.getByRole('button', { name: 'Edit', exact: true }).first().click();
    const initial = await read('/admin/store-config');
    const assetA = initial.livePages.home.sections.find(s => s.type === 'hero-banner').settings.backgroundImage;
    const versions = await read('/admin/store-config/versions');
    const versionA = versions.versions.find(v => v.isCurrent).version;
    const navA = (await read('/admin/cms/navigation')).live.announcement;
    await page.getByLabel('Background Image', { exact: true }).setInputFiles('.artifacts/homepage-invalid.png');
    await page.getByRole('alert').filter({ hasText: 'Upload failed' }).waitFor();
    const retained = await page.evaluate(async () => (await import('/src/modules/storefront/store/index.js')).useBuilderStore.getState().sections.find(s => s.type === 'hero-banner').settings.backgroundImage);
    if (retained !== assetA) throw new Error('Invalid file corrupted the draft');
    await page.screenshot({ path: '.artifacts/homepage-invalid-upload-preserves-draft.png' });
    await status('invalid upload certified');
    const replacementResponse = page.waitForResponse(r => r.url().endsWith('/admin/homepage-media') && r.request().method() === 'POST');
    await page.getByLabel('Background Image', { exact: true }).setInputFiles('.artifacts/media-cert-b.png');
    const replacement = await (await replacementResponse).json();
    await page.waitForFunction(async reference => (await import('/src/modules/storefront/store/index.js')).useBuilderStore.getState().sections.find(s => s.type === 'hero-banner').settings.backgroundImage === reference, replacement.reference);
    await page.getByRole('img', { name: 'Image preview', exact: true }).evaluate(i => i.decode());
    const assetB = await page.evaluate(async () => (await import('/src/modules/storefront/store/index.js')).useBuilderStore.getState().sections.find(s => s.type === 'hero-banner').settings.backgroundImage);
    if (assetB === assetA) throw new Error('Replacement did not create an immutable asset');
    const savedResponse = page.waitForResponse(r => r.url().endsWith('/admin/store-config/pages/home') && r.request().method() === 'PUT');
    await page.getByRole('button', { name: 'Save Draft', exact: true }).click();
    await savedResponse;
    await clean();
    await page.waitForTimeout(350);
    await page.reload();
    await status('saved replacement reloaded');
    await page.getByRole('button', { name: 'Discard', exact: true }).waitFor();
    const discardResponse = page.waitForResponse(r => r.url().endsWith('/admin/store-config/pages/home') && r.request().method() === 'PUT');
    await page.getByRole('button', { name: 'Discard', exact: true }).click();
    await discardResponse;
    await page.waitForFunction(async expected => (await import('/src/modules/storefront/store/index.js')).useBuilderStore.getState().sections.find(s => s.type === 'hero-banner').settings.backgroundImage === expected, assetA);
    await clean();
    const discarded = await read('/admin/store-config');
    if (discarded.pages.home.sections.find(s => s.type === 'hero-banner').settings.backgroundImage !== assetA) throw new Error('Discard did not persist the published asset');
    await status('discard certified');
    await page.getByRole('button', { name: 'Edit', exact: true }).first().click();
    const publishedReplacementResponse = page.waitForResponse(r => r.url().endsWith('/admin/homepage-media') && r.request().method() === 'POST');
    await page.getByLabel('Background Image', { exact: true }).setInputFiles('.artifacts/media-cert-b.png');
    const publishedReplacement = await (await publishedReplacementResponse).json();
    await page.waitForFunction(async reference => (await import('/src/modules/storefront/store/index.js')).useBuilderStore.getState().sections.find(s => s.type === 'hero-banner').settings.backgroundImage === reference, publishedReplacement.reference);
    await page.getByRole('img', { name: 'Image preview', exact: true }).evaluate(i => i.decode());
    const publishedB = await page.evaluate(async () => (await import('/src/modules/storefront/store/index.js')).useBuilderStore.getState().sections.find(s => s.type === 'hero-banner').settings.backgroundImage);
    await page.getByRole('button', { name: 'Publish Homepage', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Publish Homepage', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await live.reload();
    await live.locator('header').waitFor();
    const afterPublish = await live.evaluate(async ({ a, b }) => ({ a: (await fetch(a, { cache: 'no-store' })).status, b: (await fetch(b, { cache: 'no-store' })).status }), { a: assetA, b: publishedB });
    if (afterPublish.a !== 404 || afterPublish.b !== 200) throw new Error('Replaced asset delivery authority is stale');
    await status('replacement published');
    await page.goto('http://localhost:5173/storefront/navigation?view=header');
    await page.getByLabel('Announcement text (English)', { exact: true }).fill('CERT Rollback Changed Announcement');
    await page.getByRole('button', { name: 'Publish Header and Footer Navigation', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Publish Header and Footer Navigation', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await page.waitForTimeout(350);
    await page.goto('http://localhost:5173/storefront/storeconfig-version-history');
    await status('rollback history loaded');
    await page.getByRole('heading', { name: `Version ID v${versionA}`, exact: true }).locator('xpath=../../../..').getByRole('button', { name: 'Rollback', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByRole('checkbox').check();
    await dialog.getByRole('textbox').fill('Homepage media and Header announcement browser certification');
    await dialog.getByRole('button', { name: 'Rollback Now', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    const restored = await read('/admin/store-config');
    const navRestored = (await read('/admin/cms/navigation')).live.announcement;
    if (restored.livePages.home.sections.find(s => s.type === 'hero-banner').settings.backgroundImage !== assetA || JSON.stringify(navRestored) !== JSON.stringify(navA)) throw new Error('Rollback did not restore image and Header snapshot');
    await live.reload();
    await live.waitForFunction(async text => (await import('/src/stores/navigationStore.ts')).useNavigationStore.getState().navigation?.header.announcement?.text === text, navA.text);
    const afterRollback = await live.evaluate(async ({ a, b }) => ({ a: (await fetch(a, { cache: 'no-store' })).status, b: (await fetch(b, { cache: 'no-store' })).status }), { a: assetA, b: publishedB });
    if (afterRollback.a !== 200 || afterRollback.b !== 404) throw new Error('Rollback image delivery authority is stale');
    await live.screenshot({ path: '.artifacts/homepage-media-announcement-rollback-live.png' });
    const evidence = { assetA, replacedDraftAsset: assetB, publishedB, versionA, afterPublish, afterRollback, announcementRestored: true, invalidUploadPreservedDraft: true, savedDraftDiscardRestoredPublished: true };
    await page.evaluate(evidence => sessionStorage.setItem('homepage-rollback-evidence', JSON.stringify(evidence)), evidence);
    return evidence;
    } catch (error) {
        await status(`ERROR: ${String(error)}`);
        throw error;
    }
}
