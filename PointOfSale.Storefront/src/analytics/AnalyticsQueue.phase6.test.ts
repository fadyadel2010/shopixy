import { afterEach, expect, it, vi } from 'vitest';
import type { AnalyticsEvent } from './eventTypes';
const runtime = vi.hoisted(() => ({ key: 'p6:tenant-a', send: vi.fn() }));
vi.mock('./AnalyticsClient', () => ({ sendAnalyticsBatch: runtime.send }));
vi.mock('@/bootstrap/tenantScopedStorage', () => ({ tryGetTenantScopedStorageKey: () => runtime.key }));
afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals(); vi.resetModules(); });
it('a late response from the old tenant cannot remove or persist the new tenant queue', async () => {
    vi.useFakeTimers();
    const storage = new Map<string, string>();
    vi.stubGlobal('localStorage', { getItem: (key: string) => storage.get(key) ?? null, setItem: (key: string, value: string) => storage.set(key, value) });
    vi.stubGlobal('window', { addEventListener: vi.fn() });
    vi.stubGlobal('document', { addEventListener: vi.fn() });
    let finish: ((value: unknown) => void) | undefined;
    runtime.send.mockImplementationOnce(() => new Promise(resolve => { finish = resolve }));
    const { analyticsQueue } = await import('./AnalyticsQueue');
    const event = (eventId: string) => ({ eventId, type: 'PageView', actor: { sessionId: 'p6-session' }, context: { pageUrl: '/' } }) as AnalyticsEvent;
    analyticsQueue.enqueue(event('old'));
    const pending = analyticsQueue.flush();
    runtime.key = 'p6:tenant-b';
    analyticsQueue.enqueue(event('new'));
    finish?.({ accepted: 1, rejected: 0, acceptedEventIds: ['old'], errors: [] });
    await pending;
    expect(analyticsQueue.getQueueLength()).toBe(1);
    expect(storage.get('p6:tenant-b')).toContain('new');
    expect(storage.get('p6:tenant-b')).not.toContain('old');
    runtime.send.mockResolvedValue({ accepted: 1, rejected: 0, acceptedEventIds: ['new'], errors: [] });
    await analyticsQueue.flush();
    expect(runtime.send.mock.calls[1][0][0].eventId).toBe('new');
    expect(analyticsQueue.getQueueLength()).toBe(0);
    vi.clearAllTimers();
});
