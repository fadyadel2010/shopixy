namespace PointOfSale.Core.Analytics;

/// <summary>
/// Represents WHO performed the analytics event.
/// 
/// SECURITY RULES:
/// - CustomerId is ONLY set if user is authenticated (server-validated)
/// - SessionId tracks anonymous/guest users
/// - IsAuthenticated is set by the BACKEND, never trusted from frontend
/// - Frontend claims are validated against server-side token/session
/// </summary>
public class AnalyticsActor
{
    /// <summary>
    /// The authenticated customer ID (OnlineCustomer.Id).
    /// NULL for anonymous/guest users.
    /// 
    /// SECURITY: This is resolved SERVER-SIDE from the JWT token.
    /// Frontend-provided CustomerId is IGNORED.
    /// </summary>
    public Guid? CustomerId { get; set; }

    /// <summary>
    /// Anonymous session identifier for guest tracking.
    /// Used to correlate events for the same anonymous user.
    /// 
    /// RULES:
    /// - Required for guest users
    /// - Should be a UUID generated by frontend and stored in localStorage
    /// - Backend validates format but trusts the value for analytics purposes
    /// </summary>
    public string? SessionId { get; set; }

    /// <summary>
    /// Whether the user is authenticated (logged in).
    /// 
    /// SECURITY: This is set by the BACKEND based on JWT validation.
    /// Frontend-provided value is IGNORED.
    /// </summary>
    public bool IsAuthenticated { get; set; }

    /// <summary>
    /// Validates the actor data.
    /// </summary>
    public bool IsValid()
    {
        // Either must have CustomerId (authenticated) or SessionId (guest)
        return CustomerId.HasValue || !string.IsNullOrWhiteSpace(SessionId);
    }
}
