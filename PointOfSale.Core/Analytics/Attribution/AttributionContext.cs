namespace PointOfSale.Core.Analytics.Attribution;

/// <summary>
/// Attribution context captured from the first PageView event in a session.
/// 
/// SOURCE OF UTM PARAMS:
/// - Extracted from URL query params on first PageView
/// - utm_source, utm_medium, utm_campaign, utm_content, utm_term
/// 
/// DEFAULT VALUES (when UTM params missing):
/// - Source = "direct"
/// - Medium = "none"
/// - Campaign = null
/// 
/// LIFECYCLE:
/// - Created once per session on first PageView
/// - Updated on subsequent PageViews (for LastTouch)
/// - Immutable after session ends
/// 
/// STORAGE:
/// - Hot: Redis (for realtime lookup)
/// - Cold: MongoDB (append-only for history)
/// </summary>
public class AttributionContext
{
    public Guid? SourceEventId { get; set; }
    /// <summary>
    /// Tenant identifier for multi-tenant isolation.
    /// </summary>
    public Guid TenantId { get; set; }

    /// <summary>
    /// POS-owned session identifier.
    /// NOT a cookie - generated by POS Analytics SDK.
    /// </summary>
    public string SessionId { get; set; } = string.Empty;

    /// <summary>
    /// Traffic source (e.g., facebook, google, direct, newsletter).
    /// From utm_source or inferred from referrer.
    /// </summary>
    public string Source { get; set; } = "direct";

    /// <summary>
    /// Marketing medium (e.g., cpc, organic, referral, email).
    /// From utm_medium.
    /// </summary>
    public string Medium { get; set; } = "none";

    /// <summary>
    /// Campaign name (e.g., ramadan_sale, black_friday).
    /// From utm_campaign.
    /// </summary>
    public string? Campaign { get; set; }

    /// <summary>
    /// Ad content or creative identifier.
    /// From utm_content.
    /// </summary>
    public string? Content { get; set; }

    /// <summary>
    /// Search term or keyword.
    /// From utm_term.
    /// </summary>
    public string? Term { get; set; }

    /// <summary>
    /// The referrer URL if available.
    /// Used to infer source when no UTM params present.
    /// </summary>
    public string? Referrer { get; set; }

    /// <summary>
    /// The landing page URL where the user first arrived.
    /// </summary>
    public string? LandingPageUrl { get; set; }

    /// <summary>
    /// When this attribution context was first captured (UTC).
    /// </summary>
    public DateTime CapturedAtUtc { get; set; }

    /// <summary>
    /// Optional customer ID if the user was authenticated.
    /// </summary>
    public Guid? CustomerId { get; set; }

    /// <summary>
    /// Whether this context was captured with UTM parameters
    /// or inferred from referrer/direct.
    /// </summary>
    public bool HasUtmParams => !string.IsNullOrEmpty(Campaign) ||
                                 (Source != "direct" && Medium != "none");

    /// <summary>
    /// Creates a default AttributionContext for direct traffic.
    /// </summary>
    public static AttributionContext CreateDirect(Guid tenantId, string sessionId)
    {
        return new AttributionContext
        {
            TenantId = tenantId,
            SessionId = sessionId,
            Source = "direct",
            Medium = "none",
            CapturedAtUtc = DateTime.UtcNow
        };
    }

    /// <summary>
    /// Creates an AttributionContext from UTM parameters.
    /// </summary>
    public static AttributionContext FromUtmParams(
        Guid tenantId,
        string sessionId,
        string? source,
        string? medium,
        string? campaign,
        string? content,
        string? term,
        string? referrer,
        string? landingPageUrl)
    {
        return new AttributionContext
        {
            TenantId = tenantId,
            SessionId = sessionId,
            Source = string.IsNullOrWhiteSpace(source) ? "direct" : source.ToLowerInvariant().Trim(),
            Medium = string.IsNullOrWhiteSpace(medium) ? "none" : medium.ToLowerInvariant().Trim(),
            Campaign = string.IsNullOrWhiteSpace(campaign) ? null : campaign.Trim(),
            Content = string.IsNullOrWhiteSpace(content) ? null : content.Trim(),
            Term = string.IsNullOrWhiteSpace(term) ? null : term.Trim(),
            Referrer = referrer,
            LandingPageUrl = landingPageUrl,
            CapturedAtUtc = DateTime.UtcNow
        };
    }
}
